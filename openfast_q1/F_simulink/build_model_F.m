function build_model_F(mdl, mdl_file, mode, cfg)
%BUILD_MODEL_F  Build by script the Simulink model of one feasibility case (spec_F).
%
%   build_model_F(mdl, mdl_file, mode, cfg)     mode: 'F1', 'F2' or 'F3'
%
%   The model is created in memory and saved to mdl_file (results folder; the .slx never enters
%   the repository, its SHA-256 is written by run_F in meta_F.txt).
%   cfg: fst, dur (s), DT (s), Ts (s), idx (channel indices from prepare_case_F), p (E2 rom_params),
%        beta_const_deg (F1), nlobj_name (F2/F3, nlmpc object in the base workspace),
%        ref (1 x 2), mv_init_deg, mexname (optional: MEX attempt of the NMPC block).
%
%   Blocks
%   - FAST: S-Function FAST_SFunc, parameters 'fst, dur, 0' (glue-codes/simulink/src/FAST_SFunc.c
%     l.37-40: file name, TMax, number of additional inputs = 0), sample time DT set by OpenFAST.
%     Input: 51 fixed inputs (FAST_Library.h l.72-83). Output: the channels of channels.txt.
%   - meas (MATLAB Function, rate DT): GenSpeed (rpm) -> rad/s; discrete first-order filter as in
%     DISCON.F90 (Alpha = exp(-DT*CornerFreq), GenSpeedF = GenSpeed at the first call), spec_F
%     controller.torque; x_meas = [RotSpeed (rad/s); GenSpeedF] (spec_F controller.state_estimate);
%     V = Wind1VelX (spec_F controller.wind_to_controller).
%   - act (MATLAB Function, rate DT): Q_g = rom_torque_law(GenSpeedF, beta_deg) of E2 (spec_F
%     controller.torque); P_e = 0.944*Q_g*omega_g with omega_g = measured GenSpeed in rad/s
%     (spec_F controller.electrical_power); collective pitch converted deg -> rad and sent to the
%     three blades (spec_F controller.pitch_units). Other inputs (yaw, brake, airfoil, cables) = 0.
%   - F1: constant pitch command cfg.beta_const_deg (spec_F cases.F1_openloop_sfunction).
%   - F2/F3: Nonlinear MPC Controller block (mpclib), object cfg.nlobj_name, sample time of the
%     object (Ts), measured-disturbance inport (Wind1VelX) and nlp.status outport enabled;
%     last_mv fed back through a unit delay (initial value cfg.mv_init_deg); rate transitions
%     DT <-> Ts (deterministic); the inputs of every call and the outputs are logged at Ts
%     (spec_F cases.F2_nmpc_physics.timing_method).
%   meas and act are separate blocks so that no algebraic loop is created through the NMPC.

DT = cfg.DT;  Ts = cfg.Ts;  p = cfg.p;
if bdIsLoaded(mdl), close_system(mdl, 0); end
new_system(mdl);
set_param(mdl, 'SolverType', 'Fixed-step', 'Solver', 'FixedStepDiscrete', ...
          'FixedStep', sprintf('%.17g', DT), 'StopTime', sprintf('%.17g', cfg.dur), ...
          'ReturnWorkspaceOutputs', 'on', 'SignalLogging', 'off', 'SaveTime', 'off', ...
          'SaveOutput', 'off', 'SaveState', 'off');

% --- plant -----------------------------------------------------------------------------------
add_block('simulink/User-Defined Functions/S-Function', [mdl '/FAST'], 'FunctionName', 'FAST_SFunc', ...
          'Parameters', sprintf('''%s'', %.17g, 0', cfg.fst, cfg.dur));

% --- measurement and filter (rate DT) --------------------------------------------------------
alpha = exp(-DT*p.CornerFreq);                       % DISCON.F90: Alpha = exp((LastTime-Time)*CornerFreq)
meas = sprintf([ ...
    'function [x_meas, V, wf, wg] = meas(y)\n' ...
    '%%#codegen\n' ...
    '%% generated by build_model_F.m; channel indices from channels.txt\n' ...
    'persistent wf_state\n' ...
    'wg = y(%d)*pi/30;          %% GenSpeed (rpm) -> rad/s\n' ...
    'if isempty(wf_state)\n' ...
    '    wf_state = wg;         %% DISCON.F90: GenSpeedF = GenSpeed at the first call\n' ...
    'end\n' ...
    'wf_state = (1 - %.17g)*wg + %.17g*wf_state;   %% Alpha = exp(-DT*CornerFreq)\n' ...
    'wf = wf_state;\n' ...
    'x_meas = [y(%d)*pi/30; wf_state];   %% RotSpeed (rpm) -> rad/s, filtered GenSpeed\n' ...
    'V = y(%d);                %% Wind1VelX (m/s)\n'], ...
    cfg.idx.GenSpeed, alpha, alpha, cfg.idx.RotSpeed, cfg.idx.Wind1VelX);
add_mfun(mdl, 'meas', meas);

% --- actuation (rate DT) ---------------------------------------------------------------------
F = {'VS_RtGnSp', 'VS_Rgn3MP', 'VS_RtPwr', 'VS_CtInSp', 'VS_Rgn2Sp', 'VS_Slope15', 'VS_TrGnSp', ...
     'VS_Rgn2K', 'VS_Slope25', 'VS_SySp', 'VS_MaxTq'};
pf = cellfun(@(f) sprintf('''%s'', %.17g', f, p.(f)), F, 'UniformOutput', false);
act = sprintf([ ...
    'function u = act(beta_deg, wf, wg)\n' ...
    '%%#codegen\n' ...
    '%% generated by build_model_F.m; constants = E2 rom_params (DISCON.F90 values), printed %%.17g\n' ...
    'p = struct(%s);\n' ...
    '[Qg, ~, ~] = rom_torque_law(wf, beta_deg, p);   %% E2 torque law on the filtered speed\n' ...
    'Pe = %.17g*Qg*wg;                %% E2 model.equations.electrical_power\n' ...
    'b = beta_deg*pi/180;             %% deg -> rad (FAST_Library.h: pitch inputs in rad)\n' ...
    'u = zeros(51, 1);\n' ...
    'u(1) = Qg;  u(2) = Pe;  u(5) = b;  u(6) = b;  u(7) = b;\n'], ...
    strjoin(pf, ', '), p.GenEff);
add_mfun(mdl, 'act', act);

add_line(mdl, 'FAST/1', 'meas/1', 'autorouting', 'on');
add_line(mdl, 'meas/3', 'act/2', 'autorouting', 'on');
add_line(mdl, 'meas/4', 'act/3', 'autorouting', 'on');
add_line(mdl, 'act/1', 'FAST/1', 'autorouting', 'on');

switch mode
    case 'F1'
        add_block('simulink/Sources/Constant', [mdl '/beta_const'], 'Value', sprintf('%.17g', cfg.beta_const_deg));
        add_line(mdl, 'beta_const/1', 'act/1', 'autorouting', 'on');
        add_block('simulink/Sinks/Terminator', [mdl '/term_x']);
        add_block('simulink/Sinks/Terminator', [mdl '/term_V']);
        add_line(mdl, 'meas/1', 'term_x/1', 'autorouting', 'on');
        add_line(mdl, 'meas/2', 'term_V/1', 'autorouting', 'on');
    case {'F2', 'F3'}
        load_system('mpclib');
        add_block('mpclib/Nonlinear MPC Controller', [mdl '/NMPC']);
        set_param([mdl '/NMPC'], 'nlmpcobj', cfg.nlobj_name, 'md_enabled', 'on', 'status_enabled', 'on');
        if isfield(cfg, 'mexname') && ~isempty(cfg.mexname)   % MEX attempt (spec_F cases.execution_modes)
            set_param([mdl '/NMPC'], 'UseMEX', 'on', 'mexname', cfg.mexname);
        end
        rt = {'RT_x', 'RT_V'};
        for k = 1:2
            add_block('simulink/Signal Attributes/Rate Transition', [mdl '/' rt{k}], ...
                      'Integrity', 'on', 'Deterministic', 'on', 'OutPortSampleTimeOpt', 'Specify', ...
                      'OutPortSampleTime', sprintf('%.17g', Ts));
        end
        add_block('simulink/Signal Attributes/Rate Transition', [mdl '/RT_mv'], ...
                  'Integrity', 'on', 'Deterministic', 'on', 'OutPortSampleTimeOpt', 'Specify', ...
                  'OutPortSampleTime', sprintf('%.17g', DT));
        add_block('simulink/Sources/Constant', [mdl '/ref'], 'Value', mat2str(cfg.ref, 17), ...
                  'VectorParams1D', 'off', 'SampleTime', sprintf('%.17g', Ts));
        add_block('simulink/Discrete/Unit Delay', [mdl '/last_mv'], ...
                  'InitialCondition', sprintf('%.17g', cfg.mv_init_deg), 'SampleTime', sprintf('%.17g', Ts));
        add_line(mdl, 'meas/1', 'RT_x/1', 'autorouting', 'on');
        add_line(mdl, 'meas/2', 'RT_V/1', 'autorouting', 'on');
        add_line(mdl, 'RT_x/1', 'NMPC/1', 'autorouting', 'on');       % x
        add_line(mdl, 'ref/1', 'NMPC/2', 'autorouting', 'on');        % ref
        add_line(mdl, 'last_mv/1', 'NMPC/3', 'autorouting', 'on');    % last_mv
        add_line(mdl, 'RT_V/1', 'NMPC/4', 'autorouting', 'on');       % md
        add_line(mdl, 'NMPC/1', 'last_mv/1', 'autorouting', 'on');
        add_line(mdl, 'NMPC/1', 'RT_mv/1', 'autorouting', 'on');
        add_line(mdl, 'RT_mv/1', 'act/1', 'autorouting', 'on');
        % logging of every call, at Ts (spec_F cases.F2_nmpc_physics.timing_method)
        logs = {'log_x', 'RT_x/1'; 'log_lastmv', 'last_mv/1'; 'log_md', 'RT_V/1'; ...
                'log_mv', 'NMPC/1'; 'log_status', 'NMPC/2'};
        for k = 1:size(logs, 1)
            add_block('simulink/Sinks/To Workspace', [mdl '/' logs{k,1}], 'VariableName', logs{k,1}, ...
                      'SaveFormat', 'Array', 'SampleTime', sprintf('%.17g', Ts), 'MaxDataPoints', 'inf');
            add_line(mdl, logs{k,2}, [logs{k,1} '/1'], 'autorouting', 'on');
        end
    otherwise
        error('build_model_F:mode', 'Unknown mode %s.', mode);
end
save_system(mdl, mdl_file);
end

% =============================================================================================
function add_mfun(mdl, name, script)
blk = [mdl '/' name];
add_block('simulink/User-Defined Functions/MATLAB Function', blk);
rt = sfroot;
m  = rt.find('-isa', 'Simulink.BlockDiagram', 'Name', mdl);
ch = m.find('-isa', 'Stateflow.EMChart', 'Path', blk);
if numel(ch) ~= 1
    error('build_model_F:mfun', 'MATLAB Function block %s not found by the Stateflow API.', blk);
end
ch.Script = script;
end
