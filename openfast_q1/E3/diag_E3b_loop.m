function diag_E3b_loop()
%DIAG_E3B_LOOP  Exploratory diagnostic of the pitch loop on the wind cases that failed in E3b
%(after Q1-E3-QUAL-2026-10-21-b).
%
%   Run ONCE by the author from the repository root, with a single MATLAB session open, after the
%   code review (separate authorisation); never relaunched, even after a crash:
%       >> addpath('openfast_q1/E3');  diag_E3b_loop
%
%   EXPLORATORY: no value of this diagnostic is publishable. Six runs of 120 s on the plant of
%   spec_E3 E3b_region3_qualification.plant_configuration (FAST_SFunc, PCMode 4, VSContrl 4,
%   discon_wrapper at every DT), on two fields generated by E3b and read in place (no copy, no
%   change): wind/U16_S31001.bts and wind/U22_S31001.bts, SHA-256 checked against wind_manifest.txt.
%   Configurations (one item changed at a time in the case copy):
%     O2_IO2  InterpOrder 2 (model value), wrapper input bp1 = pitch command of the previous DISCON
%             call (first call: measured BldPitch1), as case D-b of diag_E3W_loop
%     O2_IO1  InterpOrder 2 -> 1 (prepare_case_E3 option interp_order), same wrapper input as O2_IO2
%     O8_NC1  NumCrctn 0 -> 1 in the .fst copy (value 0 checked, exactly one line changed),
%             InterpOrder 2 (model value), wrapper input = measured BldPitch1, as run_E3b
%   discon_wrapper.m is not modified. sim is called with CaptureErrors on, so that the wrapper log
%   and the .outb written by OpenFAST are kept when OpenFAST stops the run.
%   Refuses to start (error, nothing written) under the conditions of run_E3b (tree, spec_E3,
%   binaries, DLL, wrapper commit, spec_E3W, toolbox), if wind_manifest.txt or a field differs from
%   its SHA-256, or if the output folder exists.
%   Each case runs once inside try/catch; the failure of one case does not prevent the next ones.
%   Every catch appends getReport(ME, 'extended') to errors_diag.txt. The report is appended after
%   each case. Per case: time of the first change of BldPitch1 larger than 0.1 deg in one output
%   step, max |BldPitch1|, stop time and OpenFAST message if the run stopped before 120 s, standard
%   deviation of RotSpeed over the available record, number of DISCON calls.
%   Writes in results/Q1-E3-QUAL-DIAG-<date>-a/: meta_diag.txt, report_diag.txt, summary_diag.csv,
%   errors_diag.txt (if any catch), <case>/ (case copy, model, .outb, wrapper_log.mat). Writes
%   nothing in the repository, in C:\dev, in openfast_q1/model/ or in the E3b folders.

SPEC_SHA  = '03a0b78ea895809bbea628b8ccddaba61d8edd14828c34ddc3a070e91d01587d';   % spec_E3, amendment 3
BIN_DIR   = 'C:\dev\openfast-bin';
BIN_SHA   = {'FAST_SFunc.mexw64',         '16b628c493baf4b716cfe2373f320f72f5859b38718b2dc3da455befb3112297';   % campaign.depends_on.sfunction
             'OpenFAST-Simulink_x64.dll', '2d61ae5e72c21376d87c95489a4db22d95e4c3b3d9f1aea92a8fee6daa0d093d'};  % campaign.depends_on.sfunction
DLL_REL   = 'results/Q1-E3-DISCON-BUILD-2026-10-09-a/build/DISCON.dll';                                     % campaign.depends_on.discon
DLL_SHA   = 'b922907959c41a8f1fc9db8e68b43e189ce93eabff4fa0fc2da1b83d18c8671e';
WRAP_COMMIT = '11f0133';                                                                                  % campaign.depends_on.wrapper
WRAP_SPEC = 'a78de8925221565c50f47ef458b60497891e21547d90d048f0cb38cd08bb0d86';                             % campaign.depends_on.wrapper (spec_E3W)
TB_DIR    = 'C:\dev\matlab-toolbox';
TB_COMMIT = '66256c22c8e03a8c3591439af6dc09ee1219a932';                                                    % ReadFASTbinary, as in spec_F
WIND_REL  = 'results/Q1-E3-QUAL-2026-10-21-b/wind';
MAN_SHA   = '92ceb1ff0293f10954fb9b05d6aaf5f2d653554977ad9030324f01f2a0b3e3a0';                             % wind_manifest.txt of E3b
WINDS     = {'U16_S31001', 'U22_S31001'};                                                                  % supervisor authorisation
CFG       = {'O2_IO2', 'previous command', 2, 0;                                                           % name, wrapper input, InterpOrder, NumCrctn
             'O2_IO1', 'previous command', 1, 0;
             'O8_NC1', 'measured pitch',   2, 1};
DT        = 0.00625;          % s, spec_E3W wrapper.period
TMAX      = 120;              % s, supervisor authorisation
TOL_STEP  = 0.1;              % deg per output step, supervisor authorisation
CODE = {'diag_E3b_loop.m', 'prepare_case_E3.m', 'discon_wrapper.m', 'discon.h', 'check_input_refs.m', 'run_E3b.m'};

ROOT = fileparts(fileparts(fileparts(mfilename('fullpath'))));
ED3  = fullfile(ROOT, 'openfast_q1', 'E3');
abs_ = @(rel) fullfile(ROOT, strrep(rel, '/', filesep));

% --- refusals (as run_E3b) ----------------------------------------------------------------------
if ~isempty(git_clean(ROOT)), error('diag_E3b_loop:dirty', 'openfast_q1/ is not clean in Git.'); end
if ~strcmp(sha256_file(fullfile(ED3, 'spec_E3.yaml')), SPEC_SHA)
    error('diag_E3b_loop:spec', 'spec_E3.yaml SHA-256 differs from %s.', SPEC_SHA);
end
for k = 1:size(BIN_SHA, 1)
    if ~strcmp(sha256_file(fullfile(BIN_DIR, BIN_SHA{k,1})), BIN_SHA{k,2})
        error('diag_E3b_loop:binary', '%s SHA-256 differs from spec_E3 campaign.depends_on.sfunction.', BIN_SHA{k,1});
    end
end
if ~strcmp(sha256_file(abs_(DLL_REL)), DLL_SHA), error('diag_E3b_loop:dll', 'DISCON.dll SHA-256 differs from %s.', DLL_SHA); end
[stw, wc] = system(sprintf('git -C "%s" log -1 --format=%%H -- openfast_q1/E3/discon_wrapper.m openfast_q1/E3/discon.h', ROOT));
if stw ~= 0 || ~startsWith(strtrim(wc), WRAP_COMMIT)
    error('diag_E3b_loop:wrapper', 'Last commit of the wrapper files is %s, expected %s.', strtrim(wc), WRAP_COMMIT);
end
if ~strcmp(sha256_file(fullfile(ED3, 'spec_E3W.yaml')), WRAP_SPEC)
    error('diag_E3b_loop:wrapspec', 'spec_E3W.yaml SHA-256 differs from %s.', WRAP_SPEC);
end
[~, tb] = system(sprintf('git -C "%s" rev-parse HEAD', TB_DIR));
if ~strcmp(strtrim(tb), TB_COMMIT), error('diag_E3b_loop:toolbox', 'matlab-toolbox is not at %s.', TB_COMMIT); end
WDIR = abs_(WIND_REL);
MANF = fullfile(WDIR, 'wind_manifest.txt');
if ~strcmp(sha256_file(MANF), MAN_SHA), error('diag_E3b_loop:manifest', 'wind_manifest.txt SHA-256 differs from %s.', MAN_SHA); end
ML = read_lines(MANF);
BTS = cell(numel(WINDS), 2);
for k = 1:numel(WINDS)
    i = find(startsWith(ML, [WINDS{k} ' ']));
    if ~isscalar(i), error('diag_E3b_loop:manifest', '%s not found once in wind_manifest.txt.', WINDS{k}); end
    tok = regexp(ML{i}, 'bts ([0-9a-f]{64})', 'tokens', 'once');
    if isempty(tok), error('diag_E3b_loop:manifest', 'No bts SHA-256 for %s in wind_manifest.txt.', WINDS{k}); end
    BTS(k,:) = {fullfile(WDIR, [WINDS{k} '.bts']), tok{1}};
    if ~strcmp(sha256_file(BTS{k,1}), BTS{k,2})
        error('diag_E3b_loop:bts', '%s.bts SHA-256 differs from wind_manifest.txt.', WINDS{k});
    end
end
ID  = ['Q1-E3-QUAL-DIAG-' char(datetime('now', 'Format', 'yyyy-MM-dd')) '-a'];
OUT = fullfile(ROOT, 'results', ID);
if exist(OUT, 'dir'), error('diag_E3b_loop:exists', 'Output folder already exists: %s', OUT); end
fprintf('%s\n', ID);
mkdir(OUT);

% --- meta (start) -------------------------------------------------------------------------------
[~, head] = system(sprintf('git -C "%s" rev-parse HEAD', ROOT));
M = {sprintf('campaign: %s (exploratory, not publishable)', ID), 'after: results/Q1-E3-QUAL-2026-10-21-b', ...
     sprintf('head: %s', strtrim(head)), 'clean_before: clean (openfast_q1/)', sprintf('start: %s', stamp()), ...
     sprintf('spec: openfast_q1/E3/spec_E3.yaml %s', SPEC_SHA), sprintf('spec: openfast_q1/E3/spec_E3W.yaml %s', WRAP_SPEC)};
for k = 1:numel(CODE), M{end+1} = sprintf('code: openfast_q1/E3/%s %s', CODE{k}, sha256_file(fullfile(ED3, CODE{k}))); end %#ok<AGROW>
for k = 1:size(BIN_SHA, 1), M{end+1} = sprintf('binary: %s %s', fullfile(BIN_DIR, BIN_SHA{k,1}), BIN_SHA{k,2}); end %#ok<AGROW>
M = [M, {sprintf('input: %s %s', DLL_REL, DLL_SHA), sprintf('wrapper: commit %s', strtrim(wc)), ...
         sprintf('input: %s/wind_manifest.txt %s', WIND_REL, MAN_SHA)}];
for k = 1:numel(WINDS), M{end+1} = sprintf('input: %s/%s.bts %s (read in place)', WIND_REL, WINDS{k}, BTS{k,2}); end %#ok<AGROW>
for k = 1:size(CFG, 1), M{end+1} = sprintf('config %s: wrapper input %s, InterpOrder %d, NumCrctn %d', CFG{k,:}); end %#ok<AGROW>
M = [M, {sprintf('matlab_toolbox: %s', TB_COMMIT), sprintf('matlab: %s', version), ...
         sprintf('machine: %s', strtrim(getenv('COMPUTERNAME')))}];
write_lines(fullfile(OUT, 'meta_diag.txt'), M);

% --- environment (session only, as run_E3b) -----------------------------------------------------
addpath(ED3);  addpath(BIN_DIR);  addpath(fullfile(TB_DIR, 'Utilities'));
setenv('PATH', [BIN_DIR ';' getenv('PATH')]);
cache0 = Simulink.fileGenControl('getConfig');
Simulink.fileGenControl('set', 'CacheFolder', OUT, 'CodeGenFolder', OUT);
restore = onCleanup(@() Simulink.fileGenControl('set', 'CacheFolder', cache0.CacheFolder, ...
                                                'CodeGenFolder', cache0.CodeGenFolder));
HFILE = fullfile(ED3, 'discon.h');
ERRF  = fullfile(OUT, 'errors_diag.txt');
REP   = fullfile(OUT, 'report_diag.txt');
write_lines(REP, {sprintf('campaign: %s (exploratory, not publishable)', ID)});

% --- cases --------------------------------------------------------------------------------------
rows = cell(0, 12);
extra = {};
for w = 1:numel(WINDS)
    for g = 1:size(CFG, 1)
        cs = [WINDS{w} '_' CFG{g,1}];
        L = {sprintf('--- case %s: wrapper input %s, InterpOrder %d, NumCrctn %d (start %s)', cs, CFG{g,2}, CFG{g,3}, CFG{g,4}, stamp())};
        row = {cs, WINDS{w}, CFG{g,1}, 'error', NaN, NaN, NaN, NaN, NaN, NaN, '', ''};
        try
            opt = struct('mode', 'sfunc', 'tmax', TMAX, 'dll', abs_(DLL_REL), 'dll_sha', DLL_SHA, ...
                         'bts', BTS{w,1}, 'bts_sha', BTS{w,2}, 'copy_bts', false);
            if CFG{g,3} == 1, opt.interp_order = 1; end
            cdir = fullfile(OUT, cs);
            C = prepare_case_E3(ROOT, cdir, opt);
            h0 = sha256_file(C.fst);
            if CFG{g,4} == 1
                set_fst_value(C.fst, 'NumCrctn', '0', '1');
                extra{end+1} = sprintf('%s fst: NumCrctn 0 -> 1, sha256 %s (manifest) -> %s', cs, h0, sha256_file(C.fst)); %#ok<AGROW>
            end
            io = get_fst_value(C.fst, 'InterpOrder');  nc = get_fst_value(C.fst, 'NumCrctn');
            if ~strcmp(io, sprintf('%d', CFG{g,3})) || ~strcmp(nc, sprintf('%d', CFG{g,4}))
                error('diag_E3b_loop:fst', 'InterpOrder %s, NumCrctn %s in the .fst copy, expected %d, %d.', io, nc, CFG{g,3}, CFG{g,4});
            end
            extra{end+1} = sprintf('%s fst: InterpOrder %s, NumCrctn %s, sha256 %s', cs, io, nc, sha256_file(C.fst)); %#ok<AGROW>
            [ok, wall, err, slx_sha, st, nlog] = run_case(C, cs, strcmp(CFG{g,2}, 'previous command'), DT, TMAX, ...
                                                          abs_(DLL_REL), HFILE, ERRF);
            extra{end+1} = sprintf('%s model: %s/E3bdiag.slx %s', cs, cs, slx_sha); %#ok<AGROW>
            for j = 1:numel(st.warnings), extra{end+1} = sprintf('%s warning: %s', cs, st.warnings{j}); end %#ok<AGROW>
            L{end+1} = sprintf('%s sim %s; wall %.1f s; %d DISCON calls (wrapper %.2f s); wrapper log %d rows%s', ...
                               cs, yn(ok), wall, st.ncalls, st.wall_s, nlog, errtxt(err)); %#ok<AGROW>
            row(4:6) = {yn(ok), st.ncalls, wall};
            row{12} = err;
            [D, N, chk] = read_outb(fullfile(fileparts(C.fst), '5MW_Land_DLL_WTurb.SFunc.outb'), C.channels, ERRF, cs);
            if isempty(chk)
                t  = D(:, strcmpi(N, 'Time'));
                bp = D(:, strcmpi(N, 'BldPitch1'));
                rs = D(:, strcmpi(N, 'RotSpeed'));
                k1 = find(abs(diff(bp)) > TOL_STEP, 1);
                if isempty(k1), row{7} = NaN; else, row{7} = t(k1+1); end
                row{8} = max(abs(bp));
                row{10} = std(rs);
                if t(end) < TMAX - DT/2, row{9} = t(end); end
                L{end+1} = sprintf('%s .outb: %d rows, last time %.5f s%s', cs, numel(t), t(end), ...
                                   ternary(t(end) < TMAX - DT/2, ' (stopped before 120 s)', '')); %#ok<AGROW>
                L{end+1} = sprintf('%s first |BldPitch1 change| > %.1f deg in one step: %s', cs, TOL_STEP, tstr(row{7})); %#ok<AGROW>
                L{end+1} = sprintf('%s max |BldPitch1|: %.4f deg', cs, row{8}); %#ok<AGROW>
                L{end+1} = sprintf('%s std RotSpeed over the record: %.4f rpm', cs, row{10}); %#ok<AGROW>
                row{11} = 'read';
                L{end+1} = sprintf('%s REPORTED', cs); %#ok<AGROW>
            else
                row{11} = chk;
                L{end+1} = sprintf('%s .outb NOT READ (%s)', cs, chk); %#ok<AGROW>
            end
        catch ME
            if libisloaded('DISCON'), unloadlibrary('DISCON'); end
            log_error(ERRF, ['case ' cs], ME);
            L{end+1} = sprintf('%s ERROR (%s; full report in errors_diag.txt)', cs, strrep(ME.message, newline, ' ')); %#ok<AGROW>
        end
        rows(end+1, :) = row; %#ok<AGROW>
        append_lines(REP, L);
        fprintf('%s\n', L{:});
    end
end
S = cell2table(rows, 'VariableNames', {'case', 'wind', 'config', 'sim', 'ncalls', 'wall_s', ...
               't_first_step_gt_0p1deg_s', 'max_abs_BldPitch1_deg', 't_stop_s', 'std_RotSpeed_rpm', 'outb', 'error'});
writetable(S, fullfile(OUT, 'summary_diag.csv'), 'Delimiter', ';');
append_lines(REP, {sprintf('end: %s', stamp())});
c2 = git_clean(ROOT);
if isempty(c2), ca = 'clean'; else, ca = ['NOT CLEAN: ' strrep(c2, newline, ' | ')]; end
append_lines(fullfile(OUT, 'meta_diag.txt'), [extra, {sprintf('end: %s', stamp()), ['clean_after: ' ca]}]);
end

% =============================================================================================
function [ok, wall, err, slx_sha, st, nlog] = run_case(C, cs, prev_cmd, DT, tmax, dll, hfile, errf)
% model as run_E3b run_sfunc; prev_cmd: wrapper input bp1 = previous pitch command (as D-b);
% sim with CaptureErrors on; the wrapper log is saved whatever the end of the run
mdl = 'E3bdiag';
if bdIsLoaded(mdl), close_system(mdl, 0); end
new_system(mdl);
set_param(mdl, 'SolverType', 'Fixed-step', 'Solver', 'FixedStepDiscrete', ...
          'FixedStep', sprintf('%.17g', DT), 'StopTime', sprintf('%.17g', tmax), ...
          'SaveTime', 'off', 'SaveOutput', 'off', 'SaveState', 'off', 'SignalLogging', 'off');
ix = @(name) find(strcmpi(C.channels, name));
add_block('simulink/User-Defined Functions/S-Function', [mdl '/FAST'], 'FunctionName', 'FAST_SFunc', ...
          'Parameters', sprintf('''%s'', %.17g, 0', C.fst, tmax));
if prev_cmd
    body = sprintf([ ...
        'persistent last\n' ...
        'if isempty(last), last = y(%d)*pi/180; end\n' ...
        'c = discon_wrapper(''step'', y(%d), last, y(%d)*pi/30, sqrt(y(%d)^2 + y(%d)^2));\n' ...
        'last = c(1);\n'], ...
        ix('BldPitch1'), ix('Time'), ix('GenSpeed'), ix('Wind1VelX'), ix('Wind1VelY'));
else
    body = sprintf('c = discon_wrapper(''step'', y(%d), y(%d)*pi/180, y(%d)*pi/30, sqrt(y(%d)^2 + y(%d)^2));\n', ...
        ix('Time'), ix('BldPitch1'), ix('GenSpeed'), ix('Wind1VelX'), ix('Wind1VelY'));
end
script = [sprintf([ ...
    'function [u, c] = wrap(y)\n' ...
    '%%#codegen\n' ...
    '%% generated by diag_E3b_loop.m, case %s: discon_wrapper at every DT; channel indices from channels.txt\n' ...
    'coder.extrinsic(''discon_wrapper'');\n' ...
    'c = zeros(6, 1);\n'], cs) body sprintf([ ...
    'u = zeros(51, 1);                  %% FAST_Library.h l.72-83\n' ...
    'u(1) = c(2);                       %% generator torque (N-m), wrapper.records_out\n' ...
    'u(2) = c(3);                       %% electrical power (W)\n' ...
    'u(5) = c(1);  u(6) = c(1);  u(7) = c(1);   %% collective pitch command (rad)\n'])];
add_block('simulink/User-Defined Functions/MATLAB Function', [mdl '/wrap']);
rt = sfroot;
m  = rt.find('-isa', 'Simulink.BlockDiagram', 'Name', mdl);
ch = m.find('-isa', 'Stateflow.EMChart', 'Path', [mdl '/wrap']);
if numel(ch) ~= 1, error('diag_E3b_loop:mfun', 'MATLAB Function block not found by the Stateflow API.'); end
ch.Script = script;
add_block('simulink/Sinks/To Workspace', [mdl '/log'], 'VariableName', 'wraplog', ...
          'SaveFormat', 'Structure With Time', 'MaxDataPoints', 'inf', 'Decimation', '1', ...
          'SampleTime', sprintf('%.17g', DT));
add_line(mdl, 'FAST/1', 'wrap/1', 'autorouting', 'on');
add_line(mdl, 'wrap/1', 'FAST/1', 'autorouting', 'on');
add_line(mdl, 'wrap/2', 'log/1', 'autorouting', 'on');
f = fullfile(C.case_dir, [mdl '.slx']);
save_system(mdl, f);
slx_sha = sha256_file(f);
clear('FAST_SFunc');
evalin('base', 'clear OutList');
discon_wrapper('init', dll, hfile);
ok = false;  err = '';  so = [];  nlog = 0;
w = tic;
try
    so = sim(mdl, 'ReturnWorkspaceOutputs', 'on', 'CaptureErrors', 'on');
    em = so.ErrorMessage;
    if isempty(em), ok = true; else, err = strrep(em, newline, ' '); end
catch ME
    log_error(errf, [cs ' simulation'], ME);
    err = strrep(ME.message, newline, ' ');
end
wall = toc(w);
if ~isempty(err), append_text(errf, sprintf('===== %s simulation message (%s)\n%s\n', cs, stamp(), err)); end
try
    discon_wrapper('final');                                        % final call after the simulation
catch ME
    log_error(errf, [cs ' final call'], ME);
    err = strtrim([err ' | final call: ' strrep(ME.message, newline, ' ')]);
    if libisloaded('DISCON'), unloadlibrary('DISCON'); end
end
st = discon_wrapper('stats');
if ~isempty(so)
    try
        lg = so.get('wraplog');
        t = lg.time(:);
        c = lg.signals.values;
        if ndims(c) == 3, c = reshape(permute(c, [3 1 2]), size(c, 3), []); end
        cols = {'pitch_command_rad', 'torque_Nm', 'electrical_power_W', 'record45_rad', 'record47_Nm', 'aviFAIL'};   % discon_wrapper step
        save(fullfile(C.case_dir, 'wrapper_log.mat'), 't', 'c', 'cols');
        nlog = numel(t);
    catch ME
        log_error(errf, [cs ' wrapper log'], ME);
        err = strtrim([err ' | wrapper log: ' strrep(ME.message, newline, ' ')]);
    end
end
close_system(mdl, 0);
clear('FAST_SFunc');
end

function [D, N, chk] = read_outb(outb, channels, errf, cs)
% read a .outb, complete or written by OpenFAST at a stop, and check its OutList
D = [];  N = {};  chk = '';
if ~exist(outb, 'file'), chk = 'no .outb';  return, end
try
    [D, N] = ReadFASTbinary(outb);
catch ME
    log_error(errf, [cs ' read .outb'], ME);
    chk = ['.outb not readable: ' strrep(ME.message, newline, ' ')];  return
end
N = strtrim(N(:));
if numel(N) ~= numel(channels) || ~all(strcmpi(N, channels(:)))
    chk = 'OutList written by OpenFAST differs from the expected channel list';
elseif isempty(D)
    chk = 'empty .outb';
end
end

function v = get_fst_value(f, key)
L = read_lines(f);
pat = ['^\s*(\S+)\s+' regexptranslate('escape', key) '\s'];
i = find(~cellfun(@isempty, regexp(L, pat, 'once')));
if numel(i) ~= 1, error('diag_E3b_loop:key', '%s found %d times in %s.', key, numel(i), f); end
tok = regexp(L{i}, pat, 'tokens', 'once');
v = tok{1};
end

function set_fst_value(f, key, old, new)
% value of KEY in the .fst copy: old checked, replaced by new; exactly one line changed
L0 = read_lines(f);
pat = ['^(\s*)(\S+)(\s+' regexptranslate('escape', key) '\s.*)$'];
i = find(~cellfun(@isempty, regexp(L0, pat, 'once')));
if numel(i) ~= 1, error('diag_E3b_loop:key', '%s found %d times in %s.', key, numel(i), f); end
tok = regexp(L0{i}, pat, 'tokens', 'once');
if ~strcmp(tok{2}, old), error('diag_E3b_loop:value', '%s is %s in %s, expected %s.', key, tok{2}, f, old); end
L = L0;
L{i} = [tok{1} sprintf('%*s', numel(tok{2}), new) tok{3}];
write_lines(f, L);
L1 = read_lines(f);
if numel(L1) ~= numel(L0) || nnz(~strcmp(L1, L0)) ~= 1
    error('diag_E3b_loop:value', 'The .fst copy does not differ by exactly one line after setting %s.', key);
end
end

function s = ternary(c, a, b)
if c, s = a; else, s = b; end
end

function s = tstr(t1)
if isnan(t1), s = 'none'; else, s = sprintf('t = %.5f s', t1); end
end

function log_error(f, tag, ME)
% append the full error report of a catch (getReport extended)
fid = fopen(f, 'a');
fprintf(fid, '===== %s (%s)\n%s\n', tag, stamp(), getReport(ME, 'extended', 'hyperlinks', 'off'));
fclose(fid);
end

function append_text(f, s)
fid = fopen(f, 'a');
fprintf(fid, '%s', s);
fclose(fid);
end

function s = yn(ok)
if ok, s = 'completed'; else, s = 'stopped'; end
end

function s = errtxt(e)
if isempty(e), s = ''; else, s = ['; message: ' e]; end
end

function o = git_clean(root)
